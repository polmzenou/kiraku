// Lecture des données d'un joueur pour « Télécharger mes données ». Chaque requête choisit ses champs ;
// lib/account/export.ts filtre encore par liste blanche avant d'écrire le fichier.
import type { PrismaClient } from "@/generated/prisma/client";
import { buildDataExport, type ExportInput } from "@/lib/account/export";
import { readJourney } from "@/lib/prestige/journey";

export async function collectExportWith(db: PrismaClient, userId: string, now: Date) {
  const profile = await db.user.findUnique({
    where: { id: userId },
    select: {
      id: true,
      username: true,
      email: true,
      emailVerified: true,
      image: true,
      isGuest: true,
      locale: true,
      coins: true,
      boosterStock: true,
      rankPoints: true,
      role: true,
      profileVisibility: true,
      showCollection: true,
      referralCode: true,
      termsVersion: true,
      discordLinkedAt: true,
      discordJoinedAt: true,
      v1WelcomeSeenAt: true,
      deletionRequestedAt: true,
      prestige: true,
      prestigedAt: true,
      featuredAchievement: true,
      bio: true,
      titleAgreement: true,
      vanityCode: true,
      privacyChosenAt: true,
      usernameChangedAt: true,
      lastSeenAt: true,
      bannedAt: true,
      ambassadorSince: true,
      createdAt: true,
      registeredAt: true,
    },
  });
  if (!profile) return null;

  const [
    accounts,
    cards,
    discoveries,
    wishlist,
    decks,
    abilityPurchases,
    cardLoadouts,
    expeditions,
    showcases,
    showcaseEventEntries,
    showcaseEventVotes,
    credits,
    openings,
    ledger,
    battles,
    auctions,
    bids,
    buyOrders,
    tradeListings,
    listingOffers,
    trades,
    coinFlips,
    friendships,
    blocks,
    gifts,
    missions,
    purchases,
    referrals,
    referralMilestones,
    seasons,
    review,
    notifications,
    pushSubs,
    signals,
    networkBans,
    requests,
    prestigeCycles,
    consecrated,
    provenance,
    kyaraImports,
    frescoPieces,
    frescoRewards,
  ] = await Promise.all([
    db.account.findMany({ where: { userId }, select: { provider: true, providerAccountId: true } }),
    db.userCard.findMany({
      where: { ownerId: userId },
      orderBy: { obtainedAt: "asc" },
      select: {
        id: true,
        cardId: true,
        status: true,
        obtainedAt: true,
        heritage: true,
        keptByOwner: true,
        printing: true,
        serial: true,
        card: { select: { name: true, rarity: true } },
      },
    }),
    db.discovery.findMany({
      where: { userId },
      orderBy: { createdAt: "asc" },
      select: { cardId: true, createdAt: true, regainedAt: true, imported: true, card: { select: { name: true } } },
    }),
    db.wishlistEntry.findMany({ where: { userId }, orderBy: { position: "asc" }, select: { cardId: true, position: true, createdAt: true } }),
    db.deck.findMany({ where: { userId }, orderBy: { createdAt: "asc" }, select: { id: true, name: true, cardIds: true, createdAt: true, updatedAt: true } }),
    db.abilityPurchase.findMany({
      where: { userId },
      orderBy: [{ createdAt: "asc" }, { id: "asc" }],
      select: { cardId: true, kind: true, ability: true, price: true, createdAt: true },
    }),
    db.cardLoadout.findMany({ where: { userId }, orderBy: { updatedAt: "asc" }, select: { cardId: true, keywords: true, technique: true, updatedAt: true } }),
    db.expedition.findMany({
      where: { userId },
      orderBy: { startedAt: "asc" },
      select: {
        id: true, dayKey: true, cardIds: true, status: true, outcome: true, startedAt: true, endsAt: true, settledAt: true, abandonedAt: true,
        type: { select: { slug: true } },
      },
    }),
    db.showcase.findMany({
      where: { userId },
      orderBy: [{ sortOrder: "asc" }, { createdAt: "asc" }],
      select: { id: true, name: true, layout: true, theme: true, sortOrder: true, frescoId: true, createdAt: true, updatedAt: true, items: { orderBy: { position: "asc" }, select: { position: true, userCardId: true } } },
    }),
    // Event vitrines : vitrines engagées (photo figée) et votes donnés
    db.showcaseEventEntry.findMany({
      where: { userId },
      orderBy: { createdAt: "asc" },
      select: { id: true, edition: true, showcaseId: true, name: true, layout: true, theme: true, cards: true, createdAt: true },
    }),
    db.showcaseEventVote.findMany({ where: { voterId: userId }, orderBy: { createdAt: "asc" }, select: { edition: true, entryId: true, createdAt: true, updatedAt: true } }),
    db.boosterCredit.findMany({ where: { userId }, select: { boosterTypeId: true, count: true } }),
    db.boosterOpening.findMany({
      where: { userId },
      orderBy: { createdAt: "asc" },
      select: { id: true, boosterSlug: true, catalogCardIds: true, golden: true, divine: true, pityTriggered: true, zeniSpent: true, createdAt: true },
    }),
    db.coinTransaction.findMany({
      where: { userId },
      orderBy: [{ createdAt: "asc" }, { id: "asc" }],
      select: { amount: true, reason: true, refId: true, balanceAfter: true, createdAt: true },
    }),
    db.battle.findMany({
      where: { OR: [{ p1Id: userId }, { p2Id: userId }] },
      orderBy: { createdAt: "asc" },
      select: {
        id: true,
        mode: true,
        status: true,
        p1Id: true,
        winnerSide: true,
        endReason: true,
        rewardZeni: true,
        pcDeltaP1: true,
        pcDeltaP2: true,
        botName: true,
        createdAt: true,
        endedAt: true,
        p1: { select: { username: true } },
        p2: { select: { username: true } },
      },
    }),
    db.auction.findMany({
      where: { sellerId: userId },
      orderBy: { createdAt: "asc" },
      select: { id: true, cardId: true, startPrice: true, buyoutPrice: true, finalPrice: true, fee: true, status: true, note: true, createdAt: true, endsAt: true },
    }),
    db.bid.findMany({ where: { bidderId: userId }, orderBy: { createdAt: "asc" }, select: { auctionId: true, amount: true, createdAt: true } }),
    // Avis publiés et avis remplis par le joueur ; jamais l'identité de l'autre partie
    db.buyOrder.findMany({
      where: { OR: [{ buyerId: userId }, { sellerId: userId }] },
      orderBy: { createdAt: "asc" },
      select: { id: true, buyerId: true, cardId: true, price: true, fee: true, status: true, createdAt: true, expiresAt: true, filledAt: true, closedAt: true },
    }),
    db.tradeListing.findMany({
      where: { ownerId: userId },
      orderBy: { createdAt: "asc" },
      select: { id: true, cardId: true, status: true, note: true, createdAt: true, expiresAt: true, resolvedAt: true, wants: { select: { cardId: true } } },
    }),
    db.listingOffer.findMany({
      where: { bidderId: userId },
      orderBy: { createdAt: "asc" },
      select: { listingId: true, cardId: true, status: true, createdAt: true, resolvedAt: true },
    }),
    db.trade.findMany({
      where: { OR: [{ proposerId: userId }, { recipientId: userId }] },
      orderBy: { createdAt: "asc" },
      select: {
        id: true,
        proposerId: true,
        wantedCardId: true,
        chosenCardId: true,
        status: true,
        note: true,
        declineNote: true,
        createdAt: true,
        resolvedAt: true,
      },
    }),
    // Tables de pile ou face (posées ou relevées) ; jamais la graine d'une table encore ouverte
    db.coinFlip.findMany({
      where: { OR: [{ creatorId: userId }, { opponentId: userId }] },
      orderBy: { createdAt: "asc" },
      select: {
        id: true,
        status: true,
        creatorId: true,
        creatorCardId: true,
        creatorSide: true,
        opponentCardId: true,
        seed: true,
        seedHash: true,
        result: true,
        winnerId: true,
        createdAt: true,
        resolvedAt: true,
      },
    }),
    db.friendship.findMany({
      where: { OR: [{ requesterId: userId }, { addresseeId: userId }] },
      select: {
        requesterId: true,
        status: true,
        createdAt: true,
        acceptedAt: true,
        requester: { select: { username: true } },
        addressee: { select: { username: true } },
      },
    }),
    db.userBlock.findMany({ where: { blockerId: userId }, select: { createdAt: true, blocked: { select: { username: true } } } }),
    db.gift.findMany({
      where: { OR: [{ senderId: userId }, { recipientId: userId }] },
      orderBy: { createdAt: "asc" },
      select: {
        senderId: true,
        kind: true,
        cardId: true,
        zeniSpent: true,
        createdAt: true,
        sender: { select: { username: true } },
        recipient: { select: { username: true } },
      },
    }),
    db.userMission.findMany({ where: { userId }, orderBy: { claimedAt: "asc" }, select: { missionId: true, periodKey: true, claimedAt: true } }),
    db.purchase.findMany({
      where: { userId },
      orderBy: { createdAt: "asc" },
      select: { shopItemId: true, currency: true, amount: true, status: true, createdAt: true, paidAt: true },
    }),
    db.referral.findMany({
      where: { OR: [{ referrerId: userId }, { refereeId: userId }] },
      select: {
        referrerId: true, status: true, createdAt: true, qualifiedAt: true,
        step1At: true, step2At: true, step3At: true, step4At: true, revokedAt: true, discordCreatedAt: true,
      },
    }),
    db.referralMilestoneClaim.findMany({
      where: { userId },
      orderBy: { referrals: "asc" },
      select: { referrals: true, lotId: true, claimedAt: true },
    }),
    db.seasonResult.findMany({
      where: { userId },
      select: { seasonId: true, finalPc: true, peakPc: true, peakTier: true, games: true, claimedAt: true },
    }),
    db.review.findUnique({
      where: { userId },
      select: { rating: true, body: true, reply: true, hidden: true, createdAt: true, updatedAt: true },
    }),
    db.notification.findMany({
      where: { userId },
      orderBy: { createdAt: "asc" },
      select: { type: true, refId: true, readAt: true, createdAt: true },
    }),
    db.pushSubscription.findMany({ where: { userId }, select: { endpoint: true, createdAt: true, lastSentAt: true } }),
    db.userSignal.findMany({
      where: { userId },
      orderBy: { firstSeenAt: "asc" },
      select: { kind: true, value: true, firstEvent: true, firstSeenAt: true, lastSeenAt: true },
    }),
    db.networkBan.findMany({
      where: { userId },
      orderBy: { createdAt: "asc" },
      select: { kind: true, value: true, source: true, createdAt: true, expiresAt: true, liftedAt: true },
    }),
    db.dataRequest.findMany({
      where: { userId },
      orderBy: { requestedAt: "asc" },
      select: { kind: true, status: true, requestedAt: true, dueAt: true, processedAt: true },
    }),
    db.prestigeCycle.findMany({
      where: { userId },
      orderBy: { number: "asc" },
      select: { number: true, globalRank: true, uniqueCards: true, zeni: true, heirs: true, createdAt: true },
    }),
    db.consecratedCard.findMany({
      where: { userId },
      orderBy: { consecratedAt: "asc" },
      select: { id: true, cardId: true, heritage: true, printing: true, serial: true, size: true, journey: true, consecratedAt: true, card: { select: { name: true } } },
    }),
    db.userCardOwner.findMany({ where: { ownerId: userId }, orderBy: { at: "asc" }, select: { userCardId: true, via: true, at: true } }),
    db.kyaraImport.findMany({
      where: { userId },
      orderBy: { requestedAt: "asc" },
      select: {
        id: true,
        discordId: true,
        kyaraDiscordId: true,
        kyaraUserId: true,
        kyaraUsername: true,
        status: true,
        requestedAt: true,
        readAt: true,
        appliedAt: true,
        grantedCards: true,
        grantedZeni: true,
        rejectCode: true,
        rejectNote: true,
        snapshot: true,
      },
    }),
    // Fresques : fragments obtenus et récompenses versées
    db.userFrescoPiece.findMany({
      where: { userId },
      orderBy: { obtainedAt: "asc" },
      select: { frescoId: true, obtainedAt: true, pieceId: true },
    }),
    db.frescoReward.findMany({ where: { userId }, orderBy: { grantedAt: "asc" }, select: { frescoId: true, kind: true, index: true, lotId: true, grantedAt: true } }),
  ]);

  const [
    achievements,
    chatMessages,
    sealedDrops,
    vouchers,
    lotGrants,
    teamGifts,
    ambassadorPackClaims,
    seriesCompletions,
    pollVotes,
    referralRewards,
    ennichiResults,
    ennichiAwards,
    ennichiTierGrants,
  ] = await Promise.all([
    db.userAchievement.findMany({
      where: { userId },
      orderBy: [{ unlockedAt: "asc" }, { key: "asc" }],
      select: { key: true, unlockedAt: true },
    }),
    db.chatMessage.findMany({
      where: { OR: [{ senderId: userId }, { recipientId: userId }] },
      orderBy: [{ createdAt: "asc" }, { id: "asc" }],
      select: { senderId: true, body: true, createdAt: true, readAt: true, sender: { select: { username: true } }, recipient: { select: { username: true } } },
    }),
    db.sealedDrop.findMany({
      where: { ownerId: userId },
      orderBy: { createdAt: "asc" },
      select: { id: true, boosterTypeId: true, source: true, giftable: true, createdAt: true, openedAt: true },
    }),
    db.voucher.findMany({ where: { userId }, orderBy: { createdAt: "asc" }, select: { kind: true, createdAt: true, usedAt: true, cardId: true } }),
    // Le motif saisi par l'équipe (reason) reste interne, comme celui d'un ban réseau
    db.lotGrant.findMany({ where: { userId }, orderBy: { createdAt: "asc" }, select: { lotId: true, message: true, createdAt: true } }),
    db.teamGift.findMany({
      where: { userId },
      orderBy: { createdAt: "asc" },
      select: { kind: true, cardId: true, boosterTypeId: true, quantity: true, message: true, createdAt: true },
    }),
    db.ambassadorPackClaim.findMany({ where: { userId }, orderBy: { createdAt: "asc" }, select: { periodKey: true, boosterTypeId: true, count: true, createdAt: true } }),
    db.seriesCompletion.findMany({ where: { userId }, orderBy: { completedAt: "asc" }, select: { seriesId: true, completedAt: true } }),
    db.pollVote.findMany({ where: { userId }, orderBy: { createdAt: "asc" }, select: { poll: true, answer: true, createdAt: true, updatedAt: true } }),
    db.referralReward.findMany({
      where: { userId },
      orderBy: { createdAt: "asc" },
      select: { kind: true, side: true, step: true, milestone: true, multiplier: true, lotId: true, granted: true, ennichiEdition: true, createdAt: true, clawedBackAt: true },
    }),
    db.ennichiResult.findMany({
      where: { userId },
      orderBy: [{ edition: "asc" }, { rank: "asc" }],
      select: { edition: true, rank: true, name: true, count: true, reachedAt: true, title: true },
    }),
    db.ennichiAward.findMany({ where: { userId }, orderBy: { createdAt: "asc" }, select: { edition: true, kind: true, prize: true, granted: true, createdAt: true } }),
    // Paliers de lanternes, sans l'empreinte d'IP gardée contre la fraude
    db.ennichiTierGrant.findMany({ where: { userId }, orderBy: { createdAt: "asc" }, select: { edition: true, tier: true, granted: true, createdAt: true } }),
  ]);

  // Position de chaque fragment, lue à part (une jointure de plus dans le lot parallèle ci-dessus ne passe pas partout)
  const pieceRows = frescoPieces.length ? await db.frescoPiece.findMany({ where: { id: { in: frescoPieces.map((p) => p.pieceId) } }, select: { id: true, position: true } }) : [];
  const positionOf = new Map(pieceRows.map((p) => [p.id, p.position]));
  const input: ExportInput = {
    profile,
    achievements,
    linkedAccounts: accounts,
    cards: cards.map((c) => ({
      id: c.id,
      cardId: c.cardId,
      cardName: c.card.name,
      rarity: c.card.rarity,
      status: c.status,
      obtainedAt: c.obtainedAt,
      heritage: c.heritage,
      keptByOwner: c.keptByOwner,
      printing: c.printing,
      serial: c.serial,
    })),
    discoveries: discoveries.map((d) => ({ cardId: d.cardId, cardName: d.card.name, createdAt: d.createdAt, regainedAt: d.regainedAt, imported: d.imported })),
    prestigeCycles,
    // Le parcours d'une carte consacrée cite d'autres joueurs : seuls les cycles du joueur sont exportés
    consecrated: consecrated.map(({ journey, card, ...c }) => ({ ...c, cardName: card.name, cycles: readJourney(journey).cycles })),
    provenance,
    kyaraImports,
    wishlist,
    decks,
    abilityPurchases,
    cardLoadouts,
    expeditions: expeditions.map(({ type, ...e }) => ({ ...e, typeSlug: type.slug })),
    showcases: showcases.map((s) => ({
      id: s.id,
      name: s.name,
      layout: s.layout,
      theme: s.theme,
      sortOrder: s.sortOrder,
      cards: s.items.map((i) => ({ position: i.position, userCardId: i.userCardId })),
      frescoId: s.frescoId,
      createdAt: s.createdAt,
      updatedAt: s.updatedAt,
    })),
    frescoPieces: frescoPieces.map((p) => ({ frescoId: p.frescoId, position: positionOf.get(p.pieceId) ?? null, obtainedAt: p.obtainedAt })),
    frescoRewards,
    showcaseEventEntries,
    showcaseEventVotes,
    boosterCredits: credits,
    openings,
    ledger,
    battles: battles.map((b) => {
      const side = b.p1Id === userId ? 0 : 1;
      return {
        id: b.id,
        mode: b.mode,
        status: b.status,
        side,
        opponent: side === 0 ? (b.p2?.username ?? b.botName) : b.p1.username,
        won: b.winnerSide === null ? null : b.winnerSide === side,
        endReason: b.endReason,
        rewardZeni: b.winnerSide === side ? b.rewardZeni : 0,
        pcDelta: side === 0 ? b.pcDeltaP1 : b.pcDeltaP2,
        createdAt: b.createdAt,
        endedAt: b.endedAt,
      };
    }),
    auctions,
    bids,
    buyOrders: buyOrders.map(({ buyerId, fee, ...o }) => ({ ...o, role: buyerId === userId ? "BUYER" : "SELLER", fee: buyerId === userId ? null : fee })),
    tradeListings: tradeListings.map((l) => ({ ...l, wants: l.wants.map((w) => w.cardId) })),
    listingOffers,
    trades: trades.map(({ proposerId, ...t }) => ({ ...t, direction: proposerId === userId ? "OUTGOING" : "INCOMING" })),
    coinFlips: coinFlips.map(({ creatorId, winnerId, seed, ...f }) => ({
      ...f,
      role: creatorId === userId ? "CREATOR" : "OPPONENT",
      seed: f.status === "DONE" ? seed : null,
      won: f.status === "DONE" ? winnerId === userId : null,
    })),
    friends: friendships.map((f) => {
      const outgoing = f.requesterId === userId;
      return {
        username: outgoing ? f.addressee.username : f.requester.username,
        status: f.status,
        direction: outgoing ? "OUTGOING" : "INCOMING",
        createdAt: f.createdAt,
        acceptedAt: f.acceptedAt,
      };
    }),
    blocked: blocks.map((b) => ({ username: b.blocked.username, createdAt: b.createdAt })),
    chatMessages: chatMessages.map((m) => {
      const sent = m.senderId === userId;
      return {
        direction: sent ? "SENT" : "RECEIVED",
        otherUsername: sent ? m.recipient.username : m.sender.username,
        body: m.body,
        createdAt: m.createdAt,
        readAt: m.readAt,
      };
    }),
    sealedDrops,
    vouchers,
    lotGrants,
    teamGifts,
    ambassadorPackClaims,
    seriesCompletions,
    pollVotes,
    referralRewards,
    ennichiResults,
    ennichiAwards,
    ennichiTierGrants,
    gifts: gifts.map((g) => {
      const sent = g.senderId === userId;
      return {
        direction: sent ? "SENT" : "RECEIVED",
        kind: g.kind,
        cardId: g.cardId,
        zeniSpent: sent ? g.zeniSpent : 0,
        otherUsername: sent ? g.recipient.username : g.sender.username,
        createdAt: g.createdAt,
      };
    }),
    missions,
    purchases,
    referrals: referrals.map((r) => {
      const referee = r.referrerId !== userId;
      return {
        role: referee ? "REFEREE" : "REFERRER",
        status: r.status,
        createdAt: r.createdAt,
        qualifiedAt: r.qualifiedAt,
        step1At: r.step1At,
        step2At: r.step2At,
        step3At: r.step3At,
        step4At: r.step4At,
        revokedAt: r.revokedAt,
        // Date du compte Discord du filleul : la sienne seulement, jamais celle de son ami
        discordCreatedAt: referee ? r.discordCreatedAt : null,
      };
    }),
    referralMilestones,
    seasons,
    review,
    notifications,
    pushSubscriptions: pushSubs,
    signals,
    networkBans,
    dataRequests: requests,
  };
  return buildDataExport(input, now);
}
